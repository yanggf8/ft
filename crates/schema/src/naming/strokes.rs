/// 查單字康熙筆畫。表以 codepoint 排序，binary search。
pub fn kangxi_strokes(c: char) -> Option<u8> {
    KANGXI
        .binary_search_by_key(&c, |&(ch, _)| ch)
        .ok()
        .map(|i| KANGXI[i].1)
}

